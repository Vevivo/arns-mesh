import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {runNameWitnessCommand} from '../scripts/name-witness.mjs';
import {namePolicyId,witnessKeyId,verifyNameObservation} from '../src/name-certificates.mjs';
import {NameCertificateSigner} from '../src/name-certificate-state.mjs';
import {ShardedNameSignerState} from '../src/sharded-name-state.mjs';
import {applyProfile,readNameWitnessPolicy} from '../apps/helper/network-profile.mjs';

const linuxOnly={skip:process.platform!=='linux'?'Witness enrollment requires native Linux directory fsync':false};
test('native Linux: new key enrollment, original signed vote persistence and reopen',linuxOnly,async t=>{
 const parent=fs.mkdtempSync(path.join(os.tmpdir(),'mesh-witness-cli-test-')),directory=path.join(parent,'operator');
 let root=null;
 t.after(()=>{try{root?.close();}catch{}assert.equal(path.dirname(parent),path.resolve(os.tmpdir()));fs.rmSync(parent,{recursive:true,force:true});});
 const now=Math.floor(Date.now()/60000)*60000+1000;
 const key=runNameWitnessCommand(['keygen','--data-dir',directory],{now:()=>now});
 assert.equal(fs.statSync(path.join(directory,'private-key.pem')).mode&0o777,0o600);
 assert.equal(fs.statSync(directory).mode&0o777,0o700);
 const ownPublicKey=fs.readFileSync(key.publicKeyFile,'utf8');
 const witnesses=Array.from({length:4},(_,i)=>({domain:'operator-'+i,publicKeyPem:i===0?ownPublicKey:crypto.generateKeyPairSync('ed25519').publicKey.export({type:'spki',format:'pem'})}));
 const program='1'.repeat(32),policy={schema:'arns-mesh-name-policy/v1',networkId:'native-cli-test',chainId:'solana:5eykt4UsFv8P8NJdTREpY1vzqKqZKvdp',registryProgramId:program,threshold:3,maxFaults:1,roundMs:60000,leaseMs:0,maxFutureSkewMs:1000,validFrom:now-1000,validUntil:now+86400000,witnesses};
 const policyFile=path.join(parent,'authenticated-policy.json');fs.writeFileSync(policyFile,JSON.stringify(policy));
 const peerDir=path.join(parent,'existing-peer');fs.mkdirSync(peerDir);const existing=path.join(peerDir,'retained-fixture');fs.writeFileSync(existing,'Synthetic existing data');
 applyProfile(peerDir,{schema:'arns-mesh-network-profile/v1',directPeers:['127.0.0.1:49740'],rpcSources:['127.0.0.1:8899'],arweavePeers:[],nameWitnessPolicy:policy},{now});
 const args=['enroll','--data-dir',directory,'--peer-data-dir',peerDir,'--policy',policyFile,'--policy-id',namePolicyId(policy)],enrolled=runNameWitnessCommand(args,{now:()=>now});
 assert.equal(fs.readFileSync(existing,'utf8'),'Synthetic existing data');assert.equal(namePolicyId(readNameWitnessPolicy(peerDir)),enrolled.policyId);
 const env=JSON.parse(fs.readFileSync(enrolled.configurationFile,'utf8'));
 const options={directory:env.ARNS_NAME_SIGNER_STATE,policyId:enrolled.policyId,keyId:witnessKeyId(ownPublicKey),stateEpoch:env.ARNS_NAME_SIGNER_EPOCH,now:()=>now};
 const privateKeyPem=fs.readFileSync(env.ARNS_NAME_SIGNER_KEY,'utf8');
 const observation={schema:'arns-mesh-coherent-name-observation/v1',name:'vevivo',chainId:policy.chainId,genesisHash:policy.chainId.slice(7),registryProgramId:program,antId:program,antProgramId:program,txId:'A'.repeat(43),slot:100,observedAt:new Date(now).toISOString(),leaseEndsAt:null,provenance:{coherentAccountRead:true,strictAssetValidation:true,finalizedCommitmentRequested:true,genesisChecked:true}};
 root=new ShardedNameSignerState(options);
 const signer=new NameCertificateSigner({policy,privateKeyPem,driverForName:name=>root.forName(name),now:()=>now,observe:async()=>observation});
 const first=await signer.issue('vevivo');
 assert.equal(verifyNameObservation(first,policy,{name:'vevivo',round:Math.floor(now/60000),now}).record.txId,observation.txId);
 root.close();root=new ShardedNameSignerState(options);
 const restarted=new NameCertificateSigner({policy,privateKeyPem,driverForName:name=>root.forName(name),now:()=>now,observe:async()=>{throw new Error('same-round cached signature should be retained');}});
 assert.deepEqual(await restarted.issue('vevivo'),first);
 assert.throws(()=>runNameWitnessCommand(args,{now:()=>now}),/already_enrolled_or_interrupted/);
});
